import { Link } from "@tanstack/react-router";
import { ArrowRight, RotateCcw } from "lucide-react";

import { Button } from "@/components/ui/button";
import { SafetyNotice, SectionIntro, StatusBadge } from "@/components/saarthi-ui";

export type AssessmentUrgency = "routine" | "moderate" | "urgent";

export type AssessmentResult = {
  urgency: AssessmentUrgency;
  careLevel: string;
  department: string;
} | null;

/**
 * §13 — AI Assessment Result.
 *
 * Phase 1 note: this component renders whatever result it is given.
 * It never invents an urgency level, care level, or department itself.
 * Until Phase 2 wires the real AI Edge Function response into this
 * page, `result` stays null and the honest "not yet available" state
 * below is shown instead — never a fabricated placeholder result.
 */
export function AssessmentResultPage({
  result,
  onStartOver,
}: {
  result: AssessmentResult;
  onStartOver: () => void;
}) {
  return (
    <div className="rounded-3xl border border-border/70 bg-card/75 p-6 shadow-brand sm:p-8">
      <SectionIntro
        eyebrow="Assessment result"
        title="Your next safe step"
        description="This result is generated by decision-support software based on what you shared. It is not a medical diagnosis."
      />

      {result ? (
        <div className="mt-7 space-y-5">
          <div className="flex flex-wrap items-center gap-3 rounded-2xl border border-border/70 bg-background/60 p-4">
            <span className="text-sm font-semibold text-muted-foreground">Urgency category</span>
            <StatusBadge status={result.urgency === "urgent" ? "urgent" : result.urgency === "moderate" ? "pending" : "available"} />
          </div>

          <div className="grid gap-4 sm:grid-cols-2">
            <div className="rounded-2xl border border-border/70 bg-background/60 p-4">
              <p className="text-xs font-semibold uppercase tracking-[0.14em] text-muted-foreground">Appropriate care level</p>
              <p className="mt-1.5 text-sm font-medium text-foreground">{result.careLevel}</p>
            </div>
            <div className="rounded-2xl border border-border/70 bg-background/60 p-4">
              <p className="text-xs font-semibold uppercase tracking-[0.14em] text-muted-foreground">Suggested department</p>
              <p className="mt-1.5 text-sm font-medium text-foreground">{result.department}</p>
            </div>
          </div>

          <div className="mt-2">
            <SafetyNotice emergency={result.urgency === "urgent"} />
          </div>

          <div className="flex flex-wrap items-center gap-3 pt-2">
            <Button asChild className="rounded-full">
              <Link to="/patient/facilities">
                Find Appropriate Facility <ArrowRight />
              </Link>
            </Button>
            <Button variant="ghost" onClick={onStartOver}>
              <RotateCcw /> Start Over
            </Button>
          </div>
        </div>
      ) : (
        <div className="mt-7 space-y-5">
          <div className="rounded-2xl border border-dashed border-border bg-card/60 p-6 text-center">
            <p className="text-sm font-medium text-foreground">Your result is not available yet.</p>
            <p className="mt-2 text-sm leading-relaxed text-muted-foreground">
              Decision-support results appear here once your assessment has been processed. No urgency category, care
              level, or department has been invented or assumed.
            </p>
          </div>
          <SafetyNotice emergency />
          <div className="flex flex-wrap items-center gap-3 pt-2">
            <Button variant="outline" onClick={onStartOver}>
              <RotateCcw /> Start Over
            </Button>
          </div>
        </div>
      )}
    </div>
  );
}
